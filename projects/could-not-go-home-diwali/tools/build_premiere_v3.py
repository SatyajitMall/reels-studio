def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--stab", required=True); ap.add_argument("--layout", default=str(REEL / "analysis/stab_v3_layout.json"))
    ap.add_argument("--seq-name", default="Reel_could-not-go-home-diwali_v3b"); ap.add_argument("-o", required=True)
    a = ap.parse_args()
    lay = {p["name"]: p for p in json.loads(Path(a.layout).read_text())["placed"]}
    shots = []
    for i, (name, kind, item, src, rot, (sk, pk), interp) in enumerate(SHOTS):
        f0, f1 = CUTS[i], (CUTS[i + 1] if i + 1 < len(CUTS) else 714)
        if kind == "stab":
            p = lay[src]; src_f = p["seq_start_f"] + (p["in_f"] - p["src_start_f"]); item = a.stab
        else:
            src_f = src
        shots.append({"name": name, "item": item, "src": src_f, "dur": f1 - f0, "f0": f0, "rot": rot, "sc0": sk[0][1], "sc1": sk[1][1],
                      "pos0": pk[0][1:], "pos1": pk[1][1:], "interp": 0 if interp == "linear" else 5,
                      "interpret": item.startswith("16127033")})
    lines = [{"item": n, "f0": round(t0 * FPS), "f1": round(t1 * FPS), "fade": True} for n, t0, t1 in LINES]
    lines.append({"item": "end_card.png", "f0": 717, "f1": END, "fade": False})
    data = {"shots": shots, "lines": lines, "pic_end": 714, "audio": {"item": "guide_loop_v3.wav", "dur": END, "db": -1.2}}
    js = TEMPLATE.replace("__SEQNAME__", a.seq_name).replace("__END__", str(END)).replace("__DATA__", json.dumps(data))
    Path(a.o).write_text(js)
    for s in shots:
        print(f"{s['name']:22s} {s['item'][:28]:28s} src {s['src']:4d} f0 {s['f0']:3d} dur {s['dur']} rot {s['rot']} sc {s['sc0']}→{s['sc1']} pos {s['pos0']}→{s['pos1']}")
    print("wrote", a.o)


if __name__ == "__main__":
    main()
