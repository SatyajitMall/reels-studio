def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("edl", type=Path)
    ap.add_argument("--seq-id", required=True)
    ap.add_argument("--seq-name", required=True)
    ap.add_argument("--grain", required=True, help="first:last shot index (1-based, inclusive) that get grain")
    ap.add_argument("--fade-out", type=int, default=20, help="picture fade to black, frames")
    ap.add_argument("--fade-in", type=int, default=6, help="picture fade from black, frames")
    ap.add_argument("--audio-fade", type=int, default=30, help="song fade to silence, frames")
    ap.add_argument("-o", "--out", type=Path, required=True)
    a = ap.parse_args()
    d = json.loads(a.edl.read_text())
    shots, title = [], None
    fr = lambda t: int(round(t * FPS))  # noqa: E731
    for s in d["shots"]:
        f0, f1 = fr(s["start"]), fr(s["end"])
        name = Path(s["clip"]).name
        native = NATIVE.get(name, FPS)
        src = int(round(s["src_in"] * native))
        sc = s.get("scale", 50)
        s0, s1 = (sc[0][1], sc[-1][1]) if isinstance(sc, list) else (sc, None)
        pos = s.get("pos", [540, 910])
        if isinstance(pos[0], list):
            px, py, py1, px1 = pos[0][1], pos[0][2], pos[-1][2], pos[-1][1]
        else:
            px, py, py1, px1 = pos[0], pos[1], None, None
        shots.append([s["name"], name, f0, f1 - f0, src, s.get("rotation", 0), s0, s1, px, py, py1, px1])
        if "'Calcutta' title" in s.get("shows", ""):
            title = [f0, f1]
    end = fr(d["runtime"])
    gi, gj = (int(x) for x in a.grain.split(":"))
    grain = [max(6, shots[gi - 1][2]), shots[gj - 1][2] + shots[gj - 1][3]]
    song = Path(d["audio"][0]["file"]).name
    js = (TEMPLATE.replace("__TAG__", a.seq_name).replace("__EDL__", a.edl.name).replace("__SEQID__", a.seq_id)
          .replace("__SEQNAME__", a.seq_name).replace("__END__", str(end)).replace("__GRAIN__", json.dumps(grain))
          .replace("__TITLE__", json.dumps(title)).replace("__SONG__", song).replace("__SONG_IN__", str(fr(d["audio"][0]["in"])))
          .replace("__FADE_OUT__", str(a.fade_out)).replace("__FADE_IN__", str(a.fade_in)).replace("__AFADE__", str(a.audio_fade))
          .replace("__PRIM__", json.dumps(PRIM)).replace("__IMPORTS__", json.dumps(IMPORTS)).replace("__SHOTS__", json.dumps(shots)))
    a.out.write_text(js)
    print(f"✓ {a.out}: {len(shots)} shots, end {end} f ({end / FPS:.2f} s), title {title}, grain {grain}, song in {fr(d['audio'][0]['in'])} f")


if __name__ == "__main__":
    main()
