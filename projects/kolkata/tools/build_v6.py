#!/usr/bin/env python3
"""build_v6.py: write the Premiere build script (ExtendScript) for KOLKATA v6d from its EDL (reel-local).

What it builds (camera-true, effects-playbook §A0; the director's look choice comes later, on stills):
  V1 the 26 shots, frame for frame (every non-25 fps file interpreted to 25 first), with the EDL's Rotation,
     Position and Scale keys (a push = two eased keys);
  V2 cleared (v3's bloom copy was a look) · V3 the inherited adjustment layer DISABLED (camera-true) ·
  V4 cleared (no grain) · V5 the 'Kolkata' title with a 0.4 s focus-pull settle · V6 the 4:5 window matte ·
  V7 black fades (in 6 f, out 20 f) · A1 camera sound removed · A2 the needle drop and the tram bell ·
  A3 the edited song from 7.25 s at −2.5 dB, fading over the last 1.5 s.
Sources for the shots the preview pre-rendered (each shot's EDL `note` is its recipe):
  - constant slow motion → After Effects Timewarp renders (renders/ae/v6_*.mov, camera size 2160×3840, 100 %),
    framed with the camera's Scale (the EDL's pre-render Scale ÷ 2);
  - stabilise-only (C082 walkway, C089 promenade) → the camera clip; Warp Stabilizer is added afterwards
    (_es_warp_v6.jsx / stabilize_clip) and checked by render;
  - the dhakis ramp + stabilise (C047) → the preview's own render (renders/fx_preview/Oct21_C047_dhakis.mov,
    1080×1920): ae_roundtrip.py's time_remap has no Pixel Motion, so a 100 → 40 % ramp would stutter. At the
    reel's framing (Scale 108) it is 8 % upscaled.

Usage (studio root):
  python3 projects/kolkata/tools/build_v6.py projects/kolkata/analysis/edl_v6d.json --seq-id <id> --seq-name Reel_kolkata_v6 \
      -o projects/kolkata/analysis/_es_build_v6.jsx
"""
from __future__ import annotations

import argparse
import json
import subprocess
from fractions import Fraction
from pathlib import Path

FPS = 25
ROOT = (Path.home() / "Documents/reels-studio")
K = "projects/kolkata/"
# fx pre-render id → (final source, src_in s, scale divisor, warp?)
FINAL = {
    "C111_coffee_house": (K + "renders/ae/v6_C111_coffee_house.mov", 0.0, 2, False),
    "C082_walkway_pov_s40": (K + "raw/b-roll/A001_10251528_C082.mov", 2.0, 2, True),
    "C089_sunset_lamps_stab": (K + "raw/selects/A001_10251601_C089.mov", 6.4, 2, True),
    "Oct21_C047_dhakis": (K + "renders/fx_preview/Oct21_C047_dhakis.mov", 0.0, 1, False),
    "C061_boatmen": (K + "renders/ae/v6_C061_boatmen.mov", 0.0, 2, True),
    "C018_walk_red": (K + "renders/ae/v6_C018_walk_red.mov", 0.0, 2, False),
    "C028_chai": (K + "renders/ae/v6_C028_chai.mov", 0.0, 2, False),
    "C033_academy_night": (K + "renders/ae/v6_C033_academy_night.mov", 0.0, 2, False),
}
SONG = K + "music/kolkata_v6_edit.wav"
TITLE = K + "renders/overlays/title_kolkata.png"

TEMPLATE = r'''// KOLKATA v6d build → __SEQNAME__, generated by tools/build_v6.py from analysis/edl_v6d.json. Camera-true.
var K = "/Users/SATYAJIT.MALL/Documents/reels-studio/";
var OUTF = K + "projects/kolkata/analysis/_es_out.txt", PROJP = K + "projects/kolkata/premiere/kolkata.prproj";
var SEQID = "__SEQID__", SEQNAME = "__SEQNAME__", TPF = 10160640000, END = __END__;
var D = __DATA__;
function save(o) { var f = new File(OUTF); f.encoding = "UTF-8"; f.open("w"); f.write(JSON.stringify(o)); f.close(); }
function T(fr) { var t = new Time(); t.ticks = String(Math.round(fr * TPF)); return t; }
function S(sec) { var t = new Time(); t.seconds = sec; return t; }
function F(t) { return Math.round(t.ticks / TPF); }
function comp(c, n) { for (var j = 0; j < c.components.numItems; j++) { if (c.components[j].displayName == n) return c.components[j]; } return null; }
function prop(m, n) { for (var p = 0; p < m.properties.numItems; p++) { if (m.properties[p].displayName == n) return m.properties[p]; } return null; }
function count(c, n) { var k = 0; for (var j = 0; j < c.components.numItems; j++) if (c.components[j].displayName == n) k++; return k; }
function findIn(bin, name) { for (var i = 0; i < bin.children.numItems; i++) { if (bin.children[i].name == name) return bin.children[i]; } return null; }
function byPath(bin, p) { for (var i = 0; i < bin.children.numItems; i++) { var c = bin.children[i]; if (c.type != 2) { try { if (c.getMediaPath() == p) return c; } catch (e) {} } } return null; }
function bin(name) { var b = findIn(app.project.rootItem, name); if (!b) b = app.project.rootItem.createBin(name); return b; }
function item(b, p) { var it = byPath(b, K + p); if (!it) { app.project.importFiles([K + p], true, b, false); it = byPath(b, K + p); out.imported.push(p); } if (!it) throw "import failed " + p; return it; }
function clipAt(track, fr) { for (var q = 0; q < track.clips.numItems; q++) if (Math.abs(F(track.clips[q].start) - fr) < 1) return track.clips[q]; return null; }
function qeAt(qtrack, k) { var n = 0; for (var i = 0; i < qtrack.numItems; i++) { var it = qtrack.getItemAt(i); if (it.type != "Empty") { if (n == k) return it; n++; } } return null; }
function key(pr, sec, v, ease) { var t = S(sec); pr.addKey(t); pr.setValueAtKey(t, v, true); if (ease) { try { pr.setInterpolationTypeAtKey(t, 5, true); } catch (e) { out.warn.push("ease " + e); } } }
function clear(tr) { for (var k = tr.clips.numItems - 1; k >= 0; k--) tr.clips[k].remove(false, false); }
var out = {seq: SEQNAME, shots: [], err: [], warn: [], imported: [], interpreted: []};
try {
  if (app.project.path != PROJP) throw "wrong project " + app.project.path;
  var seq = null; for (var i = 0; i < app.project.sequences.numSequences; i++) if (app.project.sequences[i].sequenceID == SEQID) seq = app.project.sequences[i];
  if (!seq || seq.name != SEQNAME) throw "sequence " + SEQNAME + " not found";
  app.project.openSequence(SEQID); app.project.activeSequence = seq; app.enableQE();
  var BR = bin("02_B-Roll"), G = bin("03_Graphics"), SX = bin("05_SFX"), M = bin("06_Music");
  var V = seq.videoTracks, A = seq.audioTracks;
  clear(V[0]); clear(V[1]); clear(V[3]); clear(V[4]); clear(V[6]); clear(A[0]); clear(A[1]); clear(A[2]);
  for (var r = 0; r < D.shots.length; r++) {
    var d = D.shots[r]; var it = item(BR, d.path);
    if (d.native != 25) { it.setOverrideFrameRate(25); out.interpreted.push([d.path.split("/").pop(), d.native]); }
    it.setInPoint(T(d.src), 4); it.setOutPoint(T(d.src + d.dur), 4); V[0].overwriteClip(it, T(d.f0)); it.clearInPoint(4); it.clearOutPoint(4);
    var c = clipAt(V[0], d.f0); if (!c) throw "not placed " + d.name;
    if (F(c.end) != d.f0 + d.dur) { c.end = T(d.f0 + d.dur); }
    var m = comp(c, "Motion"); prop(m, "Rotation").setValue(d.rot, true);
    var po = prop(m, "Position"), sc = prop(m, "Scale"), t0 = c.inPoint.seconds, t1 = t0 + d.dur / 25;
    if (d.pos1) { po.setTimeVarying(true); key(po, t0, [d.pos[0] / 1080, d.pos[1] / 1920], d.ease); key(po, t1, [d.pos1[0] / 1080, d.pos1[1] / 1920], d.ease); }
    else po.setValue([d.pos[0] / 1080, d.pos[1] / 1920], true);
    if (d.sc1 !== null) { sc.setTimeVarying(true); key(sc, t0, d.sc0, d.ease); key(sc, t1, d.sc1, d.ease); } else sc.setValue(d.sc0, true);
    out.shots.push([d.name, F(c.start), F(c.end), F(c.inPoint), Math.round(c.inPoint.seconds * 1000) / 1000]);
  }
  clear(A[0]); clear(A[1]);   // camera / stock sound linked to the V1 placements
  // V3: the inherited look layer, disabled (camera-true); V6 window matte to the end
  if (V[2].clips.numItems) { var adj = V[2].clips[0]; adj.start = T(0); adj.end = T(END); adj.disabled = true; out.v3 = "disabled"; }
  if (V[5].clips.numItems) { V[5].clips[0].start = T(0); V[5].clips[0].end = T(END); }
  // V5 title, 0.4 s focus-pull settle
  var GB = qe.project.getVideoEffectByName("Gaussian Blur");
  var ti = item(G, D.title.path); V[4].overwriteClip(ti, T(D.title.f0)); var tc = V[4].clips[0]; tc.end = T(D.title.f1);
  var tq = qeAt(qe.project.getActiveSequence().getVideoTrackAt(4), 0); if (count(tc, "Gaussian Blur") == 0) tq.addVideoEffect(GB);
  prop(comp(tc, "Motion"), "Position").setValue([0.5, 0.5], true);
  var top = prop(comp(tc, "Opacity"), "Opacity"), tsc = prop(comp(tc, "Motion"), "Scale"), tbl = prop(comp(tc, "Gaussian Blur"), "Amount"), s0 = tc.inPoint.seconds;
  top.setTimeVarying(true); tsc.setTimeVarying(true); tbl.setTimeVarying(true);
  key(top, s0, 0); key(top, s0 + 0.4, 100); key(tsc, s0, 104); key(tsc, s0 + 0.4, 100); key(tbl, s0, 30); key(tbl, s0 + 0.4, 0);
  // V7 black fades
  var bl = findIn(G, "black_1080x1920.png");
  V[6].overwriteClip(bl, T(0)); var b0 = V[6].clips[0]; b0.end = T(D.fade_in + 1); var o0 = prop(comp(b0, "Opacity"), "Opacity"); o0.setTimeVarying(true); key(o0, b0.inPoint.seconds, 100); key(o0, b0.inPoint.seconds + D.fade_in / 25, 0);
  V[6].overwriteClip(bl, T(END - D.fade_out)); var b1 = clipAt(V[6], END - D.fade_out); b1.end = T(END); var o1 = prop(comp(b1, "Opacity"), "Opacity"); o1.setTimeVarying(true); key(o1, b1.inPoint.seconds, 0); key(o1, b1.inPoint.seconds + (D.fade_out - 1) / 25, 100);
  // Audio: A3 song, A2 SFX. Level = 10^((dB − 15) / 20)
  function lvl(db) { return Math.pow(10, (db - 15) / 20); }
  for (var q = 0; q < D.audio.length; q++) {
    var a = D.audio[q]; var ai = item(a.track == 2 ? M : SX, a.path);
    ai.setInPoint(S(a["in"]), 4); ai.setOutPoint(S(a["in"] + a.dur), 4); A[a.track].overwriteClip(ai, T(a.f0)); ai.clearInPoint(4); ai.clearOutPoint(4);
    var ac = clipAt(A[a.track], a.f0); if (!ac) throw "audio not placed " + a.path;
    if (a.f1 && F(ac.end) > a.f1) ac.end = T(a.f1);
    var lv = prop(comp(ac, "Volume"), "Level"); var L = lvl(a.db), i0 = ac.inPoint.seconds, i1 = ac.outPoint.seconds;
    lv.setValue(L, true);
    if (a.fade_out > 0) { lv.setTimeVarying(true); key(lv, i0, L); key(lv, i1 - a.fade_out, L); key(lv, i1 - 0.01, 0.0); }
    out["a" + (a.track + 1) + "_" + q] = [F(ac.start), F(ac.end), Math.round(i0 * 1000) / 1000, Math.round(i1 * 1000) / 1000];
  }
  A[0].setMute(1);
  out.tracks = {v1: V[0].clips.numItems, v2: V[1].clips.numItems, v3: V[2].clips.numItems, v4: V[3].clips.numItems, v5: [F(tc.start), F(tc.end)],
    v6: V[5].clips.numItems ? [F(V[5].clips[0].start), F(V[5].clips[0].end)] : null, v7: V[6].clips.numItems, a1: A[0].clips.numItems,
    a2: A[1].clips.numItems, a3: A[2].clips.numItems, seqEnd: Math.round(seq.end / TPF)};
  app.project.save();
} catch (e) { out.err.push(e.toString() + " line " + e.line); }
save(out);
'''


def native_fps(path: Path) -> Fraction:
    out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=avg_frame_rate",
                          "-of", "csv=p=0", str(path)], capture_output=True, text=True).stdout.strip().splitlines()[0]
    return Fraction(out.split(",")[0])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("edl", type=Path)
    ap.add_argument("--seq-id", required=True)
    ap.add_argument("--seq-name", required=True)
    ap.add_argument("-o", "--out", type=Path, required=True)
    a = ap.parse_args()
    d = json.loads(a.edl.read_text())
    fr = lambda t: int(round(t * FPS))  # noqa: E731
    shots, warp = [], []
    for s in d["shots"]:
        f0, f1 = fr(s["start"]), fr(s["end"])
        clip, src_in, div = s["clip"], s["src_in"], 1
        fx_id = Path(clip).stem if "/fx_preview/" in clip else None
        if fx_id:
            clip, src_in, div, w = FINAL[fx_id]
            if w:
                warp.append(s["name"])
        nat = native_fps(ROOT / clip)
        nat25 = 25 if abs(float(nat) - 25) < 0.01 else float(nat)
        src = int(round(src_in * float(nat)))
        sc = s.get("scale", 50)
        s0, s1 = (sc[0][1] / div, sc[-1][1] / div) if isinstance(sc, list) else (sc / div, None)
        pos = s.get("pos", [540, 910])
        p0, p1 = ([pos[0][1], pos[0][2]], [pos[-1][1], pos[-1][2]]) if isinstance(pos[0], list) else (pos, None)
        if not (ROOT / clip).exists():
            raise SystemExit(f"missing source for {s['name']}: {clip}")
        shots.append(dict(name=s["name"], path=clip.replace("projects/kolkata/", "projects/kolkata/"), native=nat25, src=src,
                          f0=f0, dur=f1 - f0, rot=s.get("rotation", 0), sc0=round(s0, 3), sc1=None if s1 is None else round(s1, 3),
                          pos=p0, pos1=p1, ease=bool(s.get("ease"))))
    end = fr(d["runtime"])
    audio = []
    for t in d["audio"]:
        start = float(t["start"])
        dur = float(t.get("dur", d["runtime"] - start))
        track = 2 if t["file"] == SONG else 1
        audio.append(dict(path=t["file"], track=track, f0=fr(start), f1=end, **{"in": float(t["in"])}, dur=round(dur, 3),
                          db=float(t.get("gain_db", 0)) - (2.5 if track == 2 else 0), fade_out=float(t.get("fade_out", 0))))
    title = next(o for o in d["overlays"] if o["file"].endswith("title_kolkata.png"))
    data = dict(shots=shots, audio=audio, title=dict(path=TITLE, f0=fr(title["start"]), f1=fr(title["end"])),
                fade_in=int(d["shots"][0].get("fade_in", 6)), fade_out=int(d["shots"][-1].get("fade_out", 20)))
    js = (TEMPLATE.replace("__SEQID__", a.seq_id).replace("__SEQNAME__", a.seq_name).replace("__END__", str(end))
          .replace("__DATA__", json.dumps(data)))
    a.out.write_text(js)
    print(f"✓ {a.out}: {len(shots)} shots, end {end} f, warp later on {warp}")
    for sh in shots:
        print(f"  {sh['name']:30s} f{sh['f0']:5d}+{sh['dur']:3d} src {sh['src']:4d}f @{sh['native']} rot {sh['rot']:4} sc {sh['sc0']}→{sh['sc1']} pos {sh['pos']}→{sh['pos1']}  {Path(sh['path']).name}")
    for au in audio:
        print("  audio", au)


if __name__ == "__main__":
    main()
