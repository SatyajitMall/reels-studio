#!/usr/bin/env python3
"""swap_v7.py: KOLKATA round 7, replace single V1 shots in Reel_kolkata_v7 without rebuilding the sequence (reel-local).

Why not build_v6.py: a full build clears V1/V2/V4/V5/V7/A1–A3 and disables the V3 look layer, and would lose what was
done by hand after the v6 build (the review-gate dissolve, in-point corrections, Warp on four shots, the title keys,
and now the director's Eterna look). This script touches only the named shots:
  1. writes analysis/edl_v7.json = analysis/edl_v6d.json (the v6_3 shot map) with the swapped shots;
  2. writes analysis/_es_swap_v7.jsx, which for each swapped shot removes the V1 clip at its start (no ripple),
     places the new source frame for frame (non-25 fps files interpreted to 25), sets Rotation / Position / Scale keys,
     removes the linked camera sound from A1/A2 in that range, and re-adds any Cross Dissolve that sat on the
     shot's edges (read before, re-made after, same duration).

Usage (studio root):
  python3 projects/kolkata/tools/swap_v7.py --shot 9 '<json>' --shot 18 '<json>'
  python3 projects/kolkata/tools/swap_v7.py --base projects/kolkata/analysis/edl_v7.json --shot 17 '<json>'   # later rounds
  where <json> = {"name": ..., "clip": "projects/kolkata/raw/...", "src_in": s, "scale": n | [[t, n], [t, n]],
                  "pos": [x, y], "rotation": 0, "ease": "ease", "shows": "...", "line": optional}
"""
from __future__ import annotations

import argparse
import json
import subprocess
from fractions import Fraction
from pathlib import Path

FPS = 25
ROOT = (Path.home() / "Documents/reels-studio")
EDL_IN = ROOT / "projects/kolkata/analysis/edl_v6d.json"
EDL_OUT = ROOT / "projects/kolkata/analysis/edl_v7.json"
JSX_OUT = ROOT / "projects/kolkata/analysis/_es_swap_v7.jsx"
SEQID, SEQNAME = "75dc6c7d-8a4b-41fc-8b12-25e279e82458", "Reel_kolkata_v7"

TEMPLATE = r'''// KOLKATA round 7 shot swaps in __SEQNAME__, generated by tools/swap_v7.py.
var K = "/Users/SATYAJIT.MALL/Documents/reels-studio/";
var OUTF = K + "projects/kolkata/analysis/_es_out.txt", PROJP = K + "projects/kolkata/premiere/kolkata.prproj";
var SEQID = "__SEQID__", SEQNAME = "__SEQNAME__", TPF = 10160640000;
var D = __DATA__;
function save(o) { var f = new File(OUTF); f.encoding = "UTF-8"; f.open("w"); f.write(JSON.stringify(o)); f.close(); }
function T(fr) { var t = new Time(); t.ticks = String(Math.round(fr * TPF)); return t; }
function S(sec) { var t = new Time(); t.seconds = sec; return t; }
function F(t) { return Math.round(t.ticks / TPF); }
function comp(c, n) { for (var j = 0; j < c.components.numItems; j++) { if (c.components[j].displayName == n) return c.components[j]; } return null; }
function prop(m, n) { for (var p = 0; p < m.properties.numItems; p++) { if (m.properties[p].displayName == n) return m.properties[p]; } return null; }
function findIn(bin, name) { for (var i = 0; i < bin.children.numItems; i++) { if (bin.children[i].name == name) return bin.children[i]; } return null; }
function byPath(bin, p) { for (var i = 0; i < bin.children.numItems; i++) { var c = bin.children[i]; if (c.type != 2) { try { if (c.getMediaPath() == p) return c; } catch (e) {} } } return null; }
function bin(name) { var b = findIn(app.project.rootItem, name); if (!b) b = app.project.rootItem.createBin(name); return b; }
function item(b, p) { var it = byPath(b, K + p); if (!it) { app.project.importFiles([K + p], true, b, false); it = byPath(b, K + p); out.imported.push(p); } if (!it) throw "import failed " + p; return it; }
function clipAt(track, fr) { for (var q = 0; q < track.clips.numItems; q++) if (Math.abs(F(track.clips[q].start) - fr) < 1) return track.clips[q]; return null; }
function key(pr, sec, v, ease) { var t = S(sec); pr.addKey(t); pr.setValueAtKey(t, v, true); if (ease) { try { pr.setInterpolationTypeAtKey(t, 5, true); } catch (e) { out.warn.push("ease " + e); } } }
function trans(track) { var a = []; for (var j = 0; j < track.transitions.numItems; j++) { var t = track.transitions[j]; a.push([t.name, F(t.start), F(t.end)]); } return a; }
function qeAt(qtrack, fr) { for (var i = 0; i < qtrack.numItems; i++) { var it = qtrack.getItemAt(i); if (it.type != "Empty" && Math.abs(Math.round(it.start.ticks / TPF) - fr) < 1) return it; } return null; }
var out = {seq: SEQNAME, shots: [], err: [], warn: [], imported: [], interpreted: [], removedAudio: []};
try {
  if (app.project.path != PROJP) throw "wrong project " + app.project.path;
  var seq = null; for (var i = 0; i < app.project.sequences.numSequences; i++) if (app.project.sequences[i].sequenceID == SEQID) seq = app.project.sequences[i];
  if (!seq || seq.name != SEQNAME) throw "sequence " + SEQNAME + " not found";
  app.project.openSequence(SEQID); app.project.activeSequence = seq; app.enableQE();
  var BR = bin("02_B-Roll"), V = seq.videoTracks, A = seq.audioTracks;
  out.transBefore = trans(V[0]);
  for (var r = 0; r < D.shots.length; r++) {
    var d = D.shots[r];
    var old = clipAt(V[0], d.f0); if (!old) throw "no V1 clip at " + d.f0 + " for " + d.name;
    if (F(old.end) != d.f0 + d.dur) out.warn.push(d.name + ": old clip ends " + F(old.end) + ", EDL " + (d.f0 + d.dur));
    // dissolves touching this shot's edges, to re-make afterwards
    var edge = []; for (var j = 0; j < out.transBefore.length; j++) { var tb = out.transBefore[j]; if ((tb[1] <= d.f0 && tb[2] >= d.f0) || (tb[1] <= d.f0 + d.dur && tb[2] >= d.f0 + d.dur)) edge.push(tb); }
    old.remove(false, false);
    var it = item(BR, d.path);
    if (d.native != 25) { it.setOverrideFrameRate(25); out.interpreted.push([d.path.split("/").pop(), d.native]); }
    it.setInPoint(T(d.src), 4); it.setOutPoint(T(d.src + d.dur), 4); V[0].overwriteClip(it, T(d.f0)); it.clearInPoint(4); it.clearOutPoint(4);
    var c = clipAt(V[0], d.f0); if (!c) throw "not placed " + d.name;
    if (F(c.inPoint) != d.src) { c.inPoint = T(d.src); c.start = T(d.f0); }   // in-point read-back (CR footage-catalogue item 5)
    if (F(c.end) != d.f0 + d.dur) c.end = T(d.f0 + d.dur);
    var m = comp(c, "Motion"); prop(m, "Rotation").setValue(d.rot, true);
    var po = prop(m, "Position"), sc = prop(m, "Scale"), t0 = c.inPoint.seconds, t1 = t0 + d.dur / 25;
    po.setValue([d.pos[0] / 1080, d.pos[1] / 1920], true);
    if (d.sc1 !== null) { sc.setTimeVarying(true); key(sc, t0, d.sc0, d.ease); key(sc, t1, d.sc1, d.ease); } else sc.setValue(d.sc0, true);
    // linked stock / camera sound lands on A1 (and A2 for some files): remove clips that start inside this shot
    for (var at = 0; at < 2; at++) for (var k = A[at].clips.numItems - 1; k >= 0; k--) { var ac = A[at].clips[k]; var s0 = F(ac.start); if (s0 >= d.f0 && s0 < d.f0 + d.dur && ac.projectItem && ac.projectItem.nodeId == it.nodeId) { out.removedAudio.push([at + 1, s0, F(ac.end)]); ac.remove(false, false); } }
    // re-make dissolves on its edges
    var qt = qe.project.getActiveSequence().getVideoTrackAt(0);
    for (var e = 0; e < edge.length; e++) {
      var tb = edge[e], len = tb[2] - tb[1], cut = (tb[1] + tb[2]) / 2;
      var still = false; var now = trans(V[0]); for (var n = 0; n < now.length; n++) if (now[n][1] == tb[1] && now[n][2] == tb[2]) still = true;
      if (still) continue;
      var after = qeAt(qt, Math.round(cut));
      var tc = "00;00;00;" + (len < 10 ? "0" + len : String(len));
      if (after) { after.addTransition(qe.project.getVideoTransitionByName(tb[0]), true, tc); out.warn.push("re-made " + tb.join(" ")); }
      else out.warn.push("could not re-make " + tb.join(" "));
    }
    out.shots.push([d.name, F(c.start), F(c.end), F(c.inPoint), Math.round(c.inPoint.seconds * 1000) / 1000, d.sc0, d.sc1]);
  }
  out.transAfter = trans(V[0]);
  out.v1 = V[0].clips.numItems; out.a1 = A[0].clips.numItems; out.a2 = A[1].clips.numItems; out.a3 = A[2].clips.numItems;
  out.v3 = V[2].clips.numItems ? [V[2].clips[0].disabled, F(V[2].clips[0].start), F(V[2].clips[0].end)] : null;
  app.project.save();
} catch (e) { out.err.push(e.toString() + " line " + e.line); }
save(out);
'''


def native_fps(path: Path) -> Fraction:
    out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=avg_frame_rate",
                          "-of", "csv=p=0", str(path)], capture_output=True, text=True).stdout.strip().splitlines()[0]
    return Fraction(out.split(",")[0])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--shot", nargs=2, action="append", metavar=("N", "JSON"), required=True,
                    help="1-based shot number in the base EDL and the new shot as JSON")
    ap.add_argument("--base", type=Path, default=EDL_IN,
                    help="EDL to start from (default edl_v6d.json; pass analysis/edl_v7.json for a second swap round)")
    ap.add_argument("--seq-id", default=SEQID)
    ap.add_argument("--seq-name", default=SEQNAME)
    ap.add_argument("--out", type=Path, default=EDL_OUT, help="EDL to write (default analysis/edl_v7.json)")
    a = ap.parse_args()
    edl = json.loads(a.base.read_text())
    fr = lambda t: int(round(t * FPS))  # noqa: E731
    data = []
    for n, js in a.shot:
        i = int(n) - 1
        old, new = edl["shots"][i], json.loads(js)
        nat = native_fps(ROOT / new["clip"])
        nat25 = 25 if abs(float(nat) - 25) < 0.01 else float(nat)
        rate = round(float(nat) / FPS, 4) if nat25 != 25 else 1.0     # interpreted to 25: plays at nat/25 of real time
        shot = dict(old, **{k: v for k, v in new.items() if k != "name"})
        shot["name"] = f"{i + 1:02d}_{new['name']}"
        shot["rate"] = round(1 / rate, 4) if rate != 1 else 1.0       # EDL convention: rate = playback speed (25/nat)
        shot.pop("note", None)
        edl["shots"][i] = shot
        sc = new.get("scale", 50)
        s0, s1 = (sc[0][1], sc[-1][1]) if isinstance(sc, list) else (sc, None)
        f0, f1 = fr(old["start"]), fr(old["end"])
        data.append(dict(name=shot["name"], path=new["clip"], native=nat25, src=int(round(new["src_in"] * float(nat))),
                         f0=f0, dur=f1 - f0, rot=new.get("rotation", 0), sc0=s0, sc1=s1, pos=new.get("pos", [540, 910]),
                         ease=bool(new.get("ease"))))
        print(f"shot {i + 1}: {old['name']} → {shot['name']}  f{f0}+{f1 - f0}  src {new['src_in']} s @ {nat25} fps  scale {s0}→{s1}")
    edl["note"] = edl.get("note", "") + (" Round 7 review fixes: " if a.base != EDL_IN else " Round 7: ") + "; ".join(f"shot {n} = {json.loads(j)['name']}" for n, j in a.shot) + \
        "; look = Fuji Eterna 250D → Fuji 3510 at 30 % on V3."
    a.out.write_text(json.dumps(edl, indent=1, ensure_ascii=False))
    JSX_OUT.write_text(TEMPLATE.replace("__SEQID__", a.seq_id).replace("__SEQNAME__", a.seq_name).replace("__DATA__", json.dumps(dict(shots=data))))
    print("✓", a.out, "·", JSX_OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
