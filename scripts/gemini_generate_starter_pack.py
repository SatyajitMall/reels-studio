#!/usr/bin/env python3
"""Gemini Starter Pack Generator for Cinematic Reels Studio.

Populates empty `assets/luts/`, `assets/sfx/`, and `assets/overlays/` folders with
mathematically generated, zero-dependency starter assets (prefixed with `gemini_`
so no user files are ever overwritten):

1. 5 3D .cube LUTs (33x33x33) matching `effects-playbook.md` §A3:
   - gemini_warm_film_2383.cube
   - gemini_teal_and_orange.cube
   - gemini_moody_desat.cube
   - gemini_clean_bright.cube
   - gemini_log_to_rec709.cube

2. 6 synthesized 48kHz 16-bit stereo .wav SFX matching `effects-playbook.md` §F:
   - gemini_whoosh_soft.wav
   - gemini_riser_sub_hit.wav
   - gemini_snap_swish.wav
   - gemini_text_pop_click.wav
   - gemini_camera_shutter.wav
   - gemini_bass_drop_boom.wav

3. 1 seamless 1080x1920 30fps 16mm film grain overlay (`gemini_film_grain_16mm.mp4`)
   generated via ffmpeg for Track V4 (set blend mode to Overlay or Soft Light at 20-30%).

Usage:
    ./.venv/bin/python scripts/gemini_generate_starter_pack.py
"""
from __future__ import annotations

import subprocess
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
LUTS_DIR = ROOT / "assets" / "luts"
SFX_DIR = ROOT / "assets" / "sfx"
OVERLAYS_DIR = ROOT / "assets" / "overlays"


def s_curve(x: np.ndarray, contrast: float = 1.0, pivot: float = 0.5) -> np.ndarray:
    """Smooth filmic S-curve around pivot."""
    x = np.clip(x, 0.0, 1.0)
    if abs(contrast - 1.0) < 1e-4:
        return x
    centered = x - pivot
    curved = 1.0 / (1.0 + np.exp(-contrast * 6.0 * centered))
    c_min = 1.0 / (1.0 + np.exp(-contrast * 6.0 * (0.0 - pivot)))
    c_max = 1.0 / (1.0 + np.exp(-contrast * 6.0 * (1.0 - pivot)))
    return np.clip((curved - c_min) / (c_max - c_min), 0.0, 1.0)


def write_cube_lut(path: Path, title: str, transform_fn, size: int = 33) -> None:
    """Write a standard Adobe-compatible 3D .cube LUT file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    grid = np.linspace(0.0, 1.0, size, dtype=np.float32)
    # In .cube format, R changes fastest, then G, then B
    b, g, r = np.meshgrid(grid, grid, grid, indexing="ij")
    rgb = np.stack([r, g, b], axis=-1).reshape(-1, 3)
    out_rgb = np.clip(transform_fn(rgb), 0.0, 1.0)

    lines = [
        f'TITLE "{title}"',
        "# Generated by gemini_generate_starter_pack.py for Cinematic Reels Studio",
        f"LUT_3D_SIZE {size}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
        "",
    ]
    for row in out_rgb:
        lines.append(f"{row[0]:.6f} {row[1]:.6f} {row[2]:.6f}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"✓ LUT:     {path.relative_to(ROOT)}")


def generate_luts() -> None:
    # 1. Warm Film (Kodak 2383-inspired: warm golden mids, soft toe/shoulder, slight desat in shadows)
    def warm_film(rgb: np.ndarray) -> np.ndarray:
        r, g, b = rgb[:, 0], rgb[:, 1], rgb[:, 2]
        luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
        r_c = s_curve(r, contrast=1.18, pivot=0.46)
        g_c = s_curve(g, contrast=1.15, pivot=0.47)
        b_c = s_curve(b, contrast=1.10, pivot=0.50)
        # Warm midtones/highlights, slightly cool deep shadows, soft highlight rolloff
        shadow_w = np.clip(1.0 - luma * 2.5, 0.0, 1.0)
        mid_w = np.sin(np.pi * np.clip(luma, 0.0, 1.0))
        r_out = r_c + 0.035 * mid_w - 0.010 * shadow_w
        g_out = g_c + 0.015 * mid_w
        b_out = b_c - 0.030 * mid_w + 0.015 * shadow_w
        # Slight overall saturation control (92%)
        luma_out = (0.2126 * r_out + 0.7152 * g_out + 0.0722 * b_out)[:, None]
        stacked = np.stack([r_out, g_out, b_out], axis=-1)
        return luma_out + 0.92 * (stacked - luma_out)

    # 2. Teal & Orange (cyan-teal shadows, warm skin-safe midtones/highlights)
    def teal_orange(rgb: np.ndarray) -> np.ndarray:
        r, g, b = rgb[:, 0], rgb[:, 1], rgb[:, 2]
        luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
        r_c = s_curve(r, contrast=1.20, pivot=0.48)
        g_c = s_curve(g, contrast=1.18, pivot=0.48)
        b_c = s_curve(b, contrast=1.18, pivot=0.48)
        shadow_w = (1.0 - luma) ** 1.6
        high_w = luma ** 1.4
        r_out = r_c - 0.045 * shadow_w + 0.045 * high_w
        g_out = g_c + 0.010 * shadow_w + 0.012 * high_w
        b_out = b_c + 0.055 * shadow_w - 0.040 * high_w
        return np.stack([r_out, g_out, b_out], axis=-1)

    # 3. Moody Desat (crushed shadows, cool undertone, 72% saturation, high midtone contrast)
    def moody_desat(rgb: np.ndarray) -> np.ndarray:
        r, g, b = rgb[:, 0], rgb[:, 1], rgb[:, 2]
        r_c = s_curve(r, contrast=1.26, pivot=0.52)
        g_c = s_curve(g, contrast=1.26, pivot=0.52)
        b_c = s_curve(b, contrast=1.22, pivot=0.50)
        luma = (0.2126 * r_c + 0.7152 * g_c + 0.0722 * b_c)[:, None]
        stacked = np.stack([r_c - 0.015, g_c - 0.005, b_c + 0.020], axis=-1)
        return luma + 0.72 * (stacked - luma)

    # 4. Clean Bright (lifted midtones, crisp contrast, +8% vibrance)
    def clean_bright(rgb: np.ndarray) -> np.ndarray:
        # Gentle gamma lift + subtle S-curve
        lifted = np.power(np.clip(rgb, 0.0, 1.0), 0.92)
        curved = s_curve(lifted, contrast=1.10, pivot=0.48)
        luma = (0.2126 * curved[:, 0] + 0.7152 * curved[:, 1] + 0.0722 * curved[:, 2])[:, None]
        return luma + 1.08 * (curved - luma)

    # 5. Log to Rec.709 (normalizes flat/log profiles with contrast expansion + saturation recovery)
    def log_to_rec709(rgb: np.ndarray) -> np.ndarray:
        curved = s_curve(rgb, contrast=1.42, pivot=0.46)
        luma = (0.2126 * curved[:, 0] + 0.7152 * curved[:, 1] + 0.0722 * curved[:, 2])[:, None]
        return luma + 1.22 * (curved - luma)

    write_cube_lut(LUTS_DIR / "gemini_warm_film_2383.cube", "Gemini Warm Film 2383", warm_film)
    write_cube_lut(LUTS_DIR / "gemini_teal_and_orange.cube", "Gemini Teal & Orange", teal_orange)
    write_cube_lut(LUTS_DIR / "gemini_moody_desat.cube", "Gemini Moody Desat", moody_desat)
    write_cube_lut(LUTS_DIR / "gemini_clean_bright.cube", "Gemini Clean Bright", clean_bright)
    write_cube_lut(LUTS_DIR / "gemini_log_to_rec709.cube", "Gemini Log to Rec709", log_to_rec709)


def save_stereo_wav(path: Path, left: np.ndarray, right: np.ndarray, sr: int = 48000) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    peak = max(float(np.max(np.abs(left))), float(np.max(np.abs(right))), 1e-6)
    # Normalize to -1.5 dBFS peak (~0.84)
    scale = 0.84 / peak
    stereo = np.empty((left.size * 2,), dtype=np.int16)
    stereo[0::2] = np.clip(left * scale * 32767, -32768, 32767).astype(np.int16)
    stereo[1::2] = np.clip(right * scale * 32767, -32768, 32767).astype(np.int16)
    with wave.open(str(path), "wb") as wf:
        wf.setnchannels(2)
        wf.setsampwidth(2)
        wf.setframerate(sr)
        wf.writeframes(stereo.tobytes())
    print(f"✓ SFX:     {path.relative_to(ROOT)}")


def generate_sfx(sr: int = 48000) -> None:
    rng = np.random.default_rng(42)

    # 1. Soft Whoosh (0.45s filtered noise sweep with stereo pan)
    dur = 0.45
    t = np.linspace(0, dur, int(sr * dur), endpoint=False)
    noise = rng.normal(0, 1, t.size)
    # Dynamic low-pass sweep via windowed moving average + resonant sine body
    env = np.sin(np.pi * (t / dur)) ** 2.2
    sweep_freq = 120 + 680 * np.sin(np.pi * (t / dur))
    phase = 2 * np.pi * np.cumsum(sweep_freq) / sr
    body = 0.45 * np.sin(phase) * env
    filtered = np.convolve(noise, np.ones(32) / 32, mode="same") * env
    pan = np.linspace(0.25, 0.75, t.size)
    save_stereo_wav(SFX_DIR / "gemini_whoosh_soft.wav", (body + filtered) * (1 - pan), (body + filtered) * pan, sr)

    # 2. Riser into Sub-Hit (1.6s pitch/filter riser + deep 55Hz sub impact at 1.0s)
    dur = 1.6
    t = np.linspace(0, dur, int(sr * dur), endpoint=False)
    riser_mask = t < 1.0
    t_r = t[riser_mask]
    f_r = 90.0 * (4.5 ** (t_r / 1.0))
    riser = np.sin(2 * np.pi * np.cumsum(f_r) / sr) * (t_r / 1.0) ** 2.5 * 0.5
    riser += rng.normal(0, 0.25, t_r.size) * (t_r / 1.0) ** 3.0
    hit_mask = t >= 1.0
    t_h = t[hit_mask] - 1.0
    f_h = 42.0 + 78.0 * np.exp(-t_h * 18.0)
    hit = np.sin(2 * np.pi * np.cumsum(f_h) / sr) * np.exp(-t_h * 4.5)
    sig = np.concatenate([riser, hit])
    save_stereo_wav(SFX_DIR / "gemini_riser_sub_hit.wav", sig, sig * 0.98, sr)

    # 3. Snap Swish (0.18s fast whip for punch-ins and snap zooms)
    dur = 0.18
    t = np.linspace(0, dur, int(sr * dur), endpoint=False)
    env = np.exp(-((t - 0.06) ** 2) / (2 * 0.028 ** 2))
    freq = 220 + 1400 * (t / dur)
    sig = (0.5 * np.sin(2 * np.pi * np.cumsum(freq) / sr) + 0.5 * rng.normal(0, 1, t.size)) * env
    save_stereo_wav(SFX_DIR / "gemini_snap_swish.wav", sig, sig, sr)

    # 4. Text Pop Click (0.08s warm organic pop for kinetic caption/card reveals)
    dur = 0.08
    t = np.linspace(0, dur, int(sr * dur), endpoint=False)
    freq = 520 * np.exp(-t * 45.0) + 140
    sig = np.sin(2 * np.pi * np.cumsum(freq) / sr) * np.exp(-t * 55.0)
    save_stereo_wav(SFX_DIR / "gemini_text_pop_click.wav", sig, sig, sr)

    # 5. Camera Shutter (0.16s double mechanical click for flash cuts)
    dur = 0.16
    t = np.linspace(0, dur, int(sr * dur), endpoint=False)
    click1 = rng.normal(0, 1, t.size) * np.exp(-t * 140.0)
    click2 = np.where(t > 0.055, rng.normal(0, 1, t.size) * np.exp(-np.maximum(t - 0.055, 0) * 110.0), 0.0)
    sig = click1 + 0.85 * click2
    save_stereo_wav(SFX_DIR / "gemini_camera_shutter.wav", sig, sig, sr)

    # 6. Bass Drop Boom (1.2s cinematic sub-drop for reveals/turns)
    dur = 1.2
    t = np.linspace(0, dur, int(sr * dur), endpoint=False)
    freq = 36.0 + 64.0 * np.exp(-t * 7.0)
    sig = np.tanh(1.6 * np.sin(2 * np.pi * np.cumsum(freq) / sr) * np.exp(-t * 2.8))
    save_stereo_wav(SFX_DIR / "gemini_bass_drop_boom.wav", sig, sig, sr)


def generate_grain_overlay() -> None:
    OVERLAYS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = OVERLAYS_DIR / "gemini_film_grain_16mm.mp4"
    cmd = [
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-f", "lavfi", "-i", "color=c=0x808080:s=1080x1920:r=30:d=4",
        "-vf", "noise=alls=28:allf=t+u,format=yuv420p",
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "18",
        str(out_path),
    ]
    subprocess.run(cmd, check=True)
    print(f"✓ Overlay: {out_path.relative_to(ROOT)}")


def main() -> None:
    print("Generating Gemini Cinematic Reels Starter Pack...")
    generate_luts()
    generate_sfx()
    generate_grain_overlay()
    print("\nAll starter assets generated in assets/luts/, assets/sfx/, and assets/overlays/!")


if __name__ == "__main__":
    main()
